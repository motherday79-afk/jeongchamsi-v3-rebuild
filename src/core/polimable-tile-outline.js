export function roundPolygon(points,radius=5){const edges=points.map((p,i)=>{const prev=points[(i+points.length-1)%points.length],next=points[(i+1)%points.length];const toward=q=>{const ratio=Math.min(.2,radius/Math.hypot(q[0]-p[0],q[1]-p[1]));return [p[0]+(q[0]-p[0])*ratio,p[1]+(q[1]-p[1])*ratio];};return {p,a:toward(prev),b:toward(next)};});return edges.map((e,i)=>`${i?'L':'M'}${e.a}Q${e.p} ${e.b}`).join('')+'Z';}
export function tileOutline(i){if(!outlines[i])throw Error('INVALID_TILE');const points=outlines[i].map(p=>[...p]),thickness=i%8===0?12:11;const [top,right,bottom,left]=points;const footprint=roundPolygon([top,right,[right[0],right[1]+thickness],[bottom[0],bottom[1]+thickness],[left[0],left[1]+thickness],left],5);return {points,thickness,top:roundPolygon(points,i%8===0?12:5),footprint};}
export function sideTransform(a,b,thickness,depth){const d=Math.max(0,Math.min(thickness-.5,depth)),m=(b[1]-a[1])/(b[0]-a[0]),k=a[1]-m*a[0],q=d/thickness;return [1,m*q,0,1-q,0,d+k*q];}
